# Registers, shows or removes the per-user scheduled task that keeps the fsw supervisor running.
#   powershell -ExecutionPolicy Bypass -File scripts/task.ps1 [-Status | -Unregister]
# Triggers: at this user's logon, and hourly at minute 0 Seoul (the machine's clock is Seoul time) so a
# supervisor that died is back within the hour; the pid lock makes a start while one lives a no-op.
# The action runs wscript on a generated VBScript that starts node with window style 0 and waits, so no
# console window appears and the task stays Running for as long as the supervisor lives.
# The launcher starts the supervisor again whenever it exits with 75, the code it uses to hand over to
# a newer commit.
param([switch]$Status, [switch]$Unregister)
$ErrorActionPreference = 'Stop'
$TaskName = 'fsw-supervisor'
$Repo = Split-Path -Parent $PSScriptRoot
$Instance = if ($env:FSW_INSTANCE) { $env:FSW_INSTANCE } else { Join-Path $Repo 'instance.local' }

function Show-Task {
  $task = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
  if (-not $task) { "task $TaskName not registered"; return }
  $info = $task | Get-ScheduledTaskInfo
  "task      $TaskName"
  "state     $($task.State)"
  "action    $($task.Actions[0].Execute) $($task.Actions[0].Arguments)"
  foreach ($t in $task.Triggers) {
    $kind = $t.CimClass.CimClassName -replace '^MSFT_Task|Trigger$', ''
    $rep = if ($t.Repetition.Interval) { " every $($t.Repetition.Interval)" } else { '' }
    $start = if ($t.StartBoundary) { " from $($t.StartBoundary)" } else { '' }
    "trigger   $kind$start$rep"
  }
  $s = $task.Settings
  "settings  batteries=$(-not $s.DisallowStartIfOnBatteries)/$(-not $s.StopIfGoingOnBatteries) startWhenAvailable=$($s.StartWhenAvailable) timeLimit=$($s.ExecutionTimeLimit) restart=$($s.RestartCount)x$($s.RestartInterval) instances=$($s.MultipleInstances)"
  "last run  $($info.LastRunTime) result $($info.LastTaskResult)"
  "next run  $($info.NextRunTime)"
  $lock = Join-Path $Instance 'run\supervisor.pid'
  if (Test-Path $lock) {
    $procId = [int](Get-Content $lock -TotalCount 1)
    $alive = [bool](Get-Process -Id $procId -ErrorAction SilentlyContinue)
    "lock      pid $procId alive=$alive"
  } else { 'lock      none' }
}

if ($Status) { Show-Task; exit 0 }

if ($Unregister) {
  if (Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue) {
    Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
    "task $TaskName removed"
  } else { "task $TaskName not registered" }
  exit 0
}

$node = (Get-Command node -ErrorAction Stop).Source
$runDir = Join-Path $Instance 'run'
$logDir = Join-Path $Instance 'logs'
New-Item -ItemType Directory -Force $runDir, $logDir | Out-Null
# The launcher lives in the instance, since it names this machine's paths.
$vbs = Join-Path $runDir 'fsw-run.vbs'
$cmd = 'cmd /c ""' + $node + '" "' + (Join-Path $Repo 'bin\fsw.mjs') + '" run >> "' + (Join-Path $logDir 'supervisor.log') + '" 2>&1"'
$nl = [Environment]::NewLine
$vbsText = "' Generated by scripts/task.ps1; starts the fsw supervisor hidden, waits for it, and starts it again on exit code 75." + $nl +
  'Set sh = CreateObject("WScript.Shell")' + $nl +
  'sh.CurrentDirectory = "' + $Repo + '"' + $nl +
  'Do' + $nl +
  '  rc = sh.Run("' + ($cmd -replace '"', '""') + '", 0, True)' + $nl +
  'Loop While rc = 75' + $nl +
  'WScript.Quit rc' + $nl
if (-not (Test-Path $vbs) -or (Get-Content -Raw $vbs) -ne $vbsText) { Set-Content -Path $vbs -Value $vbsText -NoNewline -Encoding ASCII }

$user = "$env:USERDOMAIN\$env:USERNAME"
$action = New-ScheduledTaskAction -Execute "$env:WINDIR\System32\wscript.exe" -Argument ('//B //Nologo "' + $vbs + '"') -WorkingDirectory $Repo
$logon = New-ScheduledTaskTrigger -AtLogOn -User $user
# Hourly at minute 0: the repetition starts at the last Seoul midnight, so every start lands on :00.
$hourly = New-ScheduledTaskTrigger -Once -At ([datetime]::Today) -RepetitionInterval (New-TimeSpan -Hours 1)
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -ExecutionTimeLimit ([TimeSpan]::Zero) -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1) -MultipleInstances IgnoreNew
$principal = New-ScheduledTaskPrincipal -UserId $user -LogonType Interactive -RunLevel Limited
Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $logon, $hourly -Settings $settings -Principal $principal -Description 'full-self-working supervisor: starts at logon, re-checked hourly at minute 0 Seoul' -Force | Out-Null
"task $TaskName registered"
Show-Task
